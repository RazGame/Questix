/**
 * Тактильный отклик на телефоне игрока.
 *
 * Android: штатный Vibration API.
 *
 * iOS: Safari его не реализует — это ограничение Apple. Подключён полифил
 * ios-vibrator-pro-max: он подменяет navigator.vibrate и добивается отклика
 * через скрытые переключатели (<input type="checkbox" switch>), которые на
 * iOS сами по себе щёлкают тактильно. Импорт делает всю работу, отдельного
 * вызова не требуется.
 *
 * Ограничение остаётся принципиальным: начиная с iOS 18.4 отклик разрешён
 * только внутри пользовательского жеста и разрешение живёт около секунды.
 * Поэтому своё нажатие отзовётся, а чужой баззер и итог раунда на айфоне —
 * нет: жеста там неоткуда взяться. На Android отзывается всё.
 */
import 'ios-vibrator-pro-max';

/** Отклик по узору (мс или массив, как у navigator.vibrate). */
export const vibrate = (pattern: number | number[]): void => {
  try {
    if (typeof navigator !== 'undefined' && 'vibrate' in navigator) {
      navigator.vibrate(0); // сбрасываем предыдущий узор, иначе они склеиваются
      navigator.vibrate(pattern);
    }
  } catch {
    /* отклик — приятное дополнение, его отсутствие не должно ломать игру */
  }
};

/**
 * Отклик, привязанный к клику. На iOS засчитывается именно click, поэтому у
 * баззера нажатие обрабатывается на pointerdown (ради скорости), а тактильный
 * отклик вешается отдельно на click.
 */
export const hapticTap = (): void => vibrate(30);
